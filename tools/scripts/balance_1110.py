def main():
    d = json.load(open(PATH, encoding="utf-8"))
    power = {}
    for rd in ROUNDS:
        for k, v in rd.items():
            power[k] = power.get(k, 1.0) * v
    out = {"_설명": NOTE}
    for k in sorted(power):
        if abs(power[k] - 1.0) > 0.0005:
            out[k] = round(power[k], 3)
    d["card_adjust"] = out
    with open(PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(d, ensure_ascii=False, indent=1) + "\n")
    print("card_adjust %d장" % (len(out) - 1))


if __name__ == "__main__":
    main()
