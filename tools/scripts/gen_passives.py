def main():
    src, dst = sys.argv[1], sys.argv[2]
    d = json.load(open(src, encoding="utf-8"))
    persons = {}
    for r in d["CARDDEF"]:
        if r[2] < 3:
            continue
        p = r[1].split(" ")[-1]
        persons.setdefault(p, {"tag": r[3], "fac": r[4]})
    rot = {}
    out = {}
    for p, info in persons.items():
        tag = info["tag"]
        i = rot.get(tag, 0)
        rot[tag] = i + 1
        s, g = OVERRIDE.get(p, (DEF_SELF[tag][i % 3], DEF_GROUP[tag][i % 3]))
        assert s in CATALOG and "scope" not in CATALOG[s], (p, s)
        assert g in CATALOG and "scope" in CATALOG[g], (p, g)
        out[p] = {"self": s, "group": g}
    data = {
        "_설명": __doc__.strip().splitlines()[0] + " 개인 특기는 고급부터, 단체 특기는 희귀부터. 같은 이름의 단체 특기는 둘까지 겹친다(두 번째는 절반).",
        "tier_scale": TIER_SCALE, "group_from_tier": 4, "base_crit": 0.05, "base_critd": 1.5,
        "catalog": CATALOG, "persons": out,
    }
    json.dump(data, open(dst, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    from collections import Counter
    print(len(out), "명 ·", "개인", dict(Counter(v["self"] for v in out.values())))
    print("단체", dict(Counter(v["group"] for v in out.values())))


main()
