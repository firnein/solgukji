def medal(im, cx, cy, side):
    side = min(side, im.width, im.height)      # 네모가 그림 밖으로 나가면(머리가 위 끝에 붙은 그림) 안으로 밀어 넣는다 —— 메달에 빈 종이 띠가 생겼다
    box = [min(max(round(cx - side / 2), 0), im.width - round(side)), min(max(round(cy - side / 2), 0), im.height - round(side))]
    box += [box[0] + round(side), box[1] + round(side)]
    s3 = SIZE * 3
    crop = im.crop(box).resize((s3, s3), Image.LANCZOS)      # 그림 밖은 투명으로 채워진다
    bg = Image.new("RGBA", (s3, s3), PAPER + (255,))
    bg.alpha_composite(crop)
    mask = Image.new("L", (s3, s3), 0)
    ImageDraw.Draw(mask).ellipse((3, 3, s3 - 4, s3 - 4), fill=255)
    bg.putalpha(mask)
    return bg.resize((SIZE, SIZE), Image.LANCZOS), box


def main():
    only = sys.argv[sys.argv.index("--only") + 1].split(",") if "--only" in sys.argv else None
    sheet = sys.argv[sys.argv.index("--sheet") + 1] if "--sheet" in sys.argv else None
    cells = []
    for nm in sorted(FACE, key=lambda s: (s.split("_")[1], s)):
        if only and nm not in only:
            continue
        p = os.path.join(SRC, nm + ".png")
        if not os.path.exists(p):
            print("그림 없음:", nm)
            continue
        im = Image.open(p).convert("RGBA")
        fx, fy, fs = FACE[nm]
        m, box = medal(im, fx * im.width, fy * im.height, fs * im.width)
        m.save(os.path.join(DST, nm + ".png"), optimize=True)
        if sheet:
            cells.append((nm, im, box, m))
    print("얼굴 메달 %d장" % (len(only) if only else len(FACE)))
    missing = [f[:-4] for f in sorted(os.listdir(SRC)) if f.endswith(".png") and f[:-4].split("_")[-1] in ("기인", "초월", "불멸", "신화") and f[:-4] not in FACE]
    if missing:
        print("표에 없는 등급 그림:", ", ".join(missing))
    if sheet:
        cols, cw, ch = 8, 236, 190
        out = Image.new("RGB", (cols * cw, ((len(cells) + cols - 1) // cols) * ch), (24, 24, 30))
        d = ImageDraw.Draw(out)
        try:
            font = ImageFont.truetype("malgun.ttf", 15)
        except OSError:
            font = ImageFont.load_default()
        for i, (nm, im, box, m) in enumerate(cells):
            ox, oy = (i % cols) * cw, (i // cols) * ch
            k = min(160 / im.height, 120 / im.width)
            th = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
            out.paste(th, (ox + 2, oy + 2), th)
            d.rectangle([ox + 2 + box[0] * k, oy + 2 + box[1] * k, ox + 2 + box[2] * k, oy + 2 + box[3] * k], outline=(255, 60, 60), width=2)
            out.paste(m.resize((108, 108), Image.LANCZOS), (ox + 124, oy + 4), m.resize((108, 108), Image.LANCZOS))
            sm = m.resize((36, 36), Image.LANCZOS)
            out.paste(sm, (ox + 160, oy + 118), sm)
            d.text((ox + 4, oy + 166), nm + (" *" if nm in HAND else ""), fill=(255, 255, 255), font=font)
        out.save(sheet)


main()
